"""
Command-line interface for the Python Auto Test Generator.

The CLI orchestrates the complete workflow:
    input validation -> Python file discovery -> test generation -> optional
    pytest/coverage/allure execution -> terminal summary.

It intentionally keeps parsing, heuristic inference, and code generation in their
own modules. This file should coordinate the pipeline, not reimplement it.
"""
from __future__ import annotations

import argparse
import importlib.util
import os
import shutil
import subprocess
import sys
from pathlib import Path
from typing import Any, Dict, Iterable, List, Optional

try:
    from rich.console import Console
    from rich.panel import Panel
    from rich.progress import Progress
    from rich.table import Table

    HAS_RICH = True
except ImportError:  # pragma: no cover - optional presentation dependency
    HAS_RICH = False

from .code_generator import generate_test_file
from .coverage_config import (
    ensure_coverage_config,
    get_coverage_cli_args,
    read_coverage_summary_from_xml,
)

console = Console() if HAS_RICH else None

_EXCLUDED_DIRS = {
    ".git",
    ".hg",
    ".svn",
    ".idea",
    ".vscode",
    ".mypy_cache",
    ".pytest_cache",
    ".ruff_cache",
    "__pycache__",
    ".venv",
    "venv",
    "env",
    "build",
    "dist",
    "htmlcov",
    "allure-results",
    "tests_output",
}

_GENERATED_PATTERNS = (
    "test_*.py",
    "*.pyc",
    ".coverage",
    "coverage.xml",
)


# ============================================================================
# PATH AND FILE DISCOVERY
# ============================================================================

def _as_abs_path(path: str | Path) -> Path:
    return Path(path).expanduser().resolve()


def _is_excluded_dir(path: Path, output_dir: Optional[Path] = None) -> bool:
    if path.name in _EXCLUDED_DIRS:
        return True
    if output_dir is not None:
        try:
            return path.resolve() == output_dir.resolve()
        except Exception:
            return False
    return False


def _is_eligible_python_file(path: Path) -> bool:
    if path.suffix != ".py":
        return False
    if path.name == "__init__.py":
        return False
    if path.name.startswith("test_"):
        return False
    return True


def _collect_python_files(
    input_path: str | Path,
    *,
    recursive: bool = True,
    output_dir: Optional[str | Path] = None,
) -> List[str]:
    """
    Collect eligible Python source files from a file or directory.

    Generated tests, cache folders, virtual environments, reports, and the
    selected output directory are excluded to avoid feeding generated artifacts
    back into the generator.
    """
    path = _as_abs_path(input_path)
    out_path = _as_abs_path(output_dir) if output_dir else None

    if path.is_file():
        return [str(path)] if _is_eligible_python_file(path) else []

    if not path.is_dir():
        return []

    files: List[Path] = []
    if recursive:
        for root, dirs, names in os.walk(path):
            root_path = Path(root)
            dirs[:] = [
                name
                for name in dirs
                if not _is_excluded_dir(root_path / name, out_path)
            ]
            for name in names:
                candidate = root_path / name
                if _is_eligible_python_file(candidate):
                    files.append(candidate.resolve())
    else:
        for candidate in path.iterdir():
            if candidate.is_file() and _is_eligible_python_file(candidate):
                files.append(candidate.resolve())

    return [str(file) for file in sorted(files)]


# ============================================================================
# SAFE OUTPUT CLEANUP
# ============================================================================

def _is_dangerous_output_dir(output_dir: Path, input_path: Path) -> bool:
    """Protect users from accidentally deleting project/root/home folders."""
    output_dir = output_dir.resolve()
    input_path = input_path.resolve()
    home = Path.home().resolve()
    cwd = Path.cwd().resolve()

    dangerous = {home, cwd, Path(output_dir.anchor).resolve()}
    if output_dir in dangerous:
        return True

    if input_path.is_file() and output_dir == input_path.parent.resolve():
        return True
    if input_path.is_dir() and output_dir == input_path:
        return True

    return False


def _remove_path(path: Path) -> None:
    if path.is_file() or path.is_symlink():
        path.unlink()
    elif path.is_dir():
        shutil.rmtree(path)


def _clean_generated_artifacts(output_dir: str | Path) -> None:
    """Remove only files/folders normally generated by this tool."""
    path = _as_abs_path(output_dir)
    if not path.exists():
        return

    for pattern in _GENERATED_PATTERNS:
        for item in path.glob(pattern):
            _remove_path(item)

    for report_dir in ("htmlcov", "allure-results", ".pytest_cache", "__pycache__"):
        item = path / report_dir
        if item.exists():
            _remove_path(item)


def _clean_output_dir(
    output_dir: str | Path,
    *,
    input_path: str | Path,
    clean_all: bool = False,
    no_clean: bool = False,
) -> None:
    path = _as_abs_path(output_dir)
    source = _as_abs_path(input_path)

    if no_clean:
        path.mkdir(parents=True, exist_ok=True)
        return

    if clean_all:
        if _is_dangerous_output_dir(path, source):
            raise ValueError(
                f"Refusing to clean dangerous output directory: {path}. "
                "Choose a dedicated output folder or omit --clean-all."
            )
        if path.exists():
            for item in path.iterdir():
                _remove_path(item)
        path.mkdir(parents=True, exist_ok=True)
        return

    path.mkdir(parents=True, exist_ok=True)
    _clean_generated_artifacts(path)


