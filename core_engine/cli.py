def _build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Auto Test Generator - AST-based Static Analysis Tool"
    )
    parser.add_argument("input", help="A Python file or directory of Python files.")
    parser.add_argument(
        "--out",
        "-o",
        default="tests_output",
        help="Directory where generated pytest files will be written.",
    )
    parser.add_argument(
        "--module",
        "-m",
        help="Optional import prefix/package path for generated imports.",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Parse files and print extracted metadata without writing files.",
    )
    parser.add_argument(
        "--verbose",
        "-v",
        action="store_true",
        help="Print per-file processing details.",
    )
    parser.add_argument(
        "--run",
        action="store_true",
        help="Run pytest immediately after generation.",
    )
    parser.add_argument(
        "--cov",
        action="store_true",
        help="Run pytest with coverage report. Requires --run and pytest-cov.",
    )
    parser.add_argument(
        "--cov-target",
        help="Explicit coverage target path/module. Defaults to input path or --module.",
    )
    parser.add_argument(
        "--allure",
        action="store_true",
        help="Generate Allure-compatible tests and run pytest with --alluredir. Requires --run and allure-pytest.",
    )
    parser.add_argument(
        "--no-recursive",
        action="store_true",
        help="When input is a directory, scan only the first level.",
    )
    parser.add_argument(
        "--no-clean",
        action="store_true",
        help="Do not clean generated artifacts in the output directory before generation.",
    )
    parser.add_argument(
        "--clean-all",
        action="store_true",
        help="Delete all contents of the output directory before generation. Refuses dangerous paths.",
    )
    return parser


def _validate_args(parser: argparse.ArgumentParser, args: argparse.Namespace) -> None:
    if args.cov and not args.run:
        parser.error("--cov requires --run")
    if args.cov_target and not args.cov:
        parser.error("--cov-target requires --cov")
    if args.allure and not args.run:
        parser.error("--allure requires --run")
    if args.dry_run and args.run:
        parser.error("--dry-run cannot be combined with --run")
    if args.no_clean and args.clean_all:
        parser.error("--no-clean and --clean-all cannot be used together")
    if args.cov and importlib.util.find_spec("pytest_cov") is None:
        parser.error("--cov requires pytest-cov to be installed")
    if args.allure and importlib.util.find_spec("allure") is None:
        parser.error("--allure requires allure-pytest to be installed")


def _generate_for_file(
    file_path: str,
    args: argparse.Namespace,
) -> Dict[str, Any]:
    try:
        return generate_test_file(
            file_path,
            args.out,
            module_path=args.module,
            dry_run=args.dry_run,
            use_allure=args.allure,
        )
    except Exception as exc:
        return {
            "status": "generation_error",
            "source_file": file_path,
            "message": f"{type(exc).__name__}: {exc}",
            "functions": [],
            "classes": [],
            "generated_tests": 0,
            "output_file": None,
            "skipped_functions": [],
        }


def main() -> None:
    parser = _build_parser()
    args = parser.parse_args()
    _validate_args(parser, args)

    input_path = _as_abs_path(args.input)
    if not input_path.exists():
        print(f"Error: path does not exist -> {args.input}")
        sys.exit(1)

    files = _collect_python_files(
        input_path,
        recursive=not args.no_recursive,
        output_dir=args.out,
    )
    if not files:
        print("Error: no eligible Python source files were found.")
        sys.exit(1)

    summary: Dict[str, Any] = {
        "scanned_files": len(files),
        "generated_test_files": 0,
        "syntax_error_files": 0,
        "generation_error_files": 0,
        "supported_callables": 0,
        "skipped_callables": 0,
        "generated_test_cases": 0,
        "unresolved_objectives": 0,
        "pytest_exit_code": None,
        "coverage_summary": {},
    }

    if not args.dry_run:
        try:
            _clean_output_dir(
                args.out,
                input_path=input_path,
                clean_all=args.clean_all,
                no_clean=args.no_clean,
            )
        except ValueError as exc:
            print(f"Error: {exc}")
            sys.exit(1)

    if HAS_RICH and not args.dry_run:
        with Progress() as progress:
            task = progress.add_task("[green]Generating tests...", total=len(files))
            for file_path in files:
                result = _generate_for_file(file_path, args)
                _update_summary(summary, result, args.verbose)
                progress.update(task, advance=1)
    else:
        for file_path in files:
            if args.verbose:
                mode = "DRY-RUN" if args.dry_run else "GENERATE"
                print(f"[{mode}] {file_path}")
            result = _generate_for_file(file_path, args)
            _update_summary(summary, result, args.verbose)
            if args.dry_run:
                _print_dry_run_details(result, verbose=args.verbose)

    pytest_exit_code: Optional[int] = None
    if args.run and not args.dry_run:
        pytest_exit_code = _run_pytest(
            args.out,
            module_path=args.module,
            input_path=args.input,
            use_cov=args.cov,
            cov_target=args.cov_target,
            use_allure=args.allure,
        )
        summary["pytest_exit_code"] = pytest_exit_code
        if args.cov:
            summary["coverage_summary"] = read_coverage_summary_from_xml("coverage.xml")

    _print_rich_summary(summary, args.dry_run)

    if pytest_exit_code is not None:
        sys.exit(pytest_exit_code)
    if summary["syntax_error_files"] or summary["generation_error_files"]:
        sys.exit(1)
    sys.exit(0)


if __name__ == "__main__":
    main()
