def _resolve_coverage_target(input_path: str | Path, module_path: Optional[str], cov_target: Optional[str]) -> str:
    if cov_target:
        return cov_target
    if module_path:
        return module_path
    return str(_as_abs_path(input_path))


def _run_pytest(
    test_dir: str,
    *,
    module_path: Optional[str],
    input_path: str,
    use_cov: bool = False,
    cov_target: Optional[str] = None,
    use_allure: bool = False,
) -> int:
    if HAS_RICH:
        console.print(Panel(f"[bold green]Running pytest on {test_dir}...[/bold green]"))
    else:
        print(f"\nRunning pytest on {test_dir}...")

    cmd = [
        sys.executable,
        "-m",
        "pytest",
        test_dir,
        "-v",
        "-p",
        "no:html",
        "-p",
        "no:jsonreport",
    ]

    if use_cov:
        target = _resolve_coverage_target(input_path, module_path, cov_target)
        source_path = _as_abs_path(input_path)
        coverage_root_hint = source_path if source_path.is_dir() else source_path.parent
        try:
            coveragerc_path = ensure_coverage_config(coverage_root_hint)
            cmd.extend(
                get_coverage_cli_args(
                    coverage_target=target,
                    include_branch=True,
                    include_term=True,
                    include_html=True,
                    include_xml=True,
                    include_json=False,
                    project_root=coverage_root_hint,
                    config_path=coveragerc_path,
                )
            )
        except Exception as exc:
            if HAS_RICH:
                console.print(f"[bold red]Coverage configuration error:[/bold red] {exc}")
            else:
                print(f"Coverage configuration error: {exc}")
            return 2

    allure_dir = "allure-results"
    if use_allure:
        cmd.append(f"--alluredir={allure_dir}")

    env = os.environ.copy()
    current_pp = env.get("PYTHONPATH", "")
    source_path = _as_abs_path(input_path)
    additional_path = source_path if source_path.is_dir() else source_path.parent
    env["PYTHONPATH"] = (
        f"{additional_path}{os.pathsep}{current_pp}" if current_pp else str(additional_path)
    )

    try:
        completed = subprocess.run(cmd, check=False, env=env)
    except Exception as exc:
        if HAS_RICH:
            console.print(f"[bold red]Error during test execution:[/bold red] {exc}")
        else:
            print(f"Error during test execution: {exc}")
        return 2

    if use_allure:
        if HAS_RICH:
            console.print(f"\n[bold blue]Allure results saved to '{allure_dir}'.[/bold blue]")
            console.print("[bold blue]To view the report, run:[/bold blue] allure serve allure-results")
        else:
            print(f"\nAllure results saved to '{allure_dir}'.")
            print("To view the report, run: allure serve allure-results")

    return completed.returncode


